W = H = 16

def rows_of(art):
    rows = [r for r in art.strip("\n").split("\n")]
    assert len(rows) == H, f"rows={len(rows)}"
    for r in rows:
        assert len(r) == W, f"width={len(r)} in {r}"
    return rows

def row_bits(row):
    v = 0
    for i, ch in enumerate(row):
        if ch == '#':
            v |= 1 << (15 - i)
    return v

def write_bmp(path, pix, w, h):
    """24bpp BMP, pix = list of (r,g,b) rows top->bottom."""
    pad = (4 - (w * 3) % 4) % 4
    size = 54 + (w * 3 + pad) * h
    import struct
    with open(path, "wb") as f:
        f.write(b'BM')
        f.write(struct.pack('<IHHI', size, 0, 0, 54))
        f.write(struct.pack('<IiiHHIIiiII', 40, w, h, 1, 24, 0, w * 3 * h, 2835, 2835, 0, 0))
        for y in range(h - 1, -1, -1):
            row = pix[y]
            for x in range(w):
                r, g, b = row[x]
                f.write(bytes((b, g, r)))
            f.write(b'\x00' * pad)

def main():
    base = "/home/z/my-project"
    out_c = os.path.join(base, "repo-check/main/camos/ui_icons.h")
    sheet = os.path.join(base, "scripts/icons_sheet.bmp")

    lines = [
        "/*",
        " * SPDX-License-Identifier: CC0-1.0",
        " *",
        " * CamBrowser UI icons: 16x16 1-bit pictograms, AUTO-GENERATED by",
        " * scripts/gen_icons.py from ASCII art. Do not edit by hand - edit the",
        " * art in the generator and re-run it. Bit 15 of each word is the",
        " * LEFTMOST pixel (same layout as the 8x8 font in app_overlay.c).",
        " *",
        " */",
        "",
        "#ifndef CAMOS_UI_ICONS_H",
        "#define CAMOS_UI_ICONS_H",
        "",
        "#include <stdint.h>",
        "",
        "#ifdef __cplusplus",
        "extern \"C\" {",
        "#endif",
        "",
        "#define UI_ICON_W 16",
        "#define UI_ICON_H 16",
        "",
        "typedef struct ui_icon {",
        "    uint16_t row[UI_ICON_H];",
        "} ui_icon_t;",
        "",
    ]
    sheet_rows = []
    for name, art in ART.items():
        rows = rows_of(art)
        words = [row_bits(r) for r in rows]
        lines.append(f"/* {name} */")
        lines.append("static const ui_icon_t __attribute__((unused)) ui_icon_%s = {" % name.lower())
        lines.append("    .row = {")
        for w in words:
            lines.append("        0x%04X," % w)
        lines.append("    }"),
        lines.append("};")
        lines.append("")
        # contact sheet row: on 32px grid, white pixels
        sheet_rows.append([[255 if r[i] == '#' else 20 for i in range(W)] for r in rows])
    lines += [
        "#ifdef __cplusplus",
        "}",
        "#endif",
        "",
        "#endif /* CAMOS_UI_ICONS_H */",
        "",
    ]
    with open(out_c, "w") as f:
        f.write("\n".join(l for l in lines if l is not None))
    print("wrote", out_c)

    # contact sheet: icons in a row, each cell 32x32 (icon 16 + margin), scaled x2
    cell = 44
    img = [[(16, 20, 32)] * (cell * len(ART)) for _ in range(cell)]
    for idx, pix in enumerate(sheet_rows):
        ox = idx * cell + 4
        oy = 12
        for y in range(H):
            for x in range(W):
                if pix[y][x] == 255:
                    for dy in range(2):
                        for dx in range(2):
                            img[oy + y * 2 + dy][ox + x * 2 + dx] = (235, 240, 252)
    write_bmp(sheet, img, cell * len(ART), cell)
    print("wrote", sheet)

if __name__ == "__main__":
    main()
