/* Map ASCII code to the font table index, -1 if not present */
static int font_index(char c)
{
    if (c < 0x20 || c > 0x7E) {
        return -1;
    }
    return c - 0x20;
}

static const uint8_t *font_glyph(char c)
{
    int idx = font_index(c);
    return (idx >= 0) ? app_overlay_font8x8[idx] : app_overlay_font8x8['?' - 0x20];
}

static void fill_rect_rgb565(uint16_t *fb, int fb_w, int fb_h,
                             int x0, int y0, int x1, int y1, uint16_t color)
{
    if (x0 < 0) x0 = 0;
    if (y0 < 0) y0 = 0;
    if (x1 > fb_w) x1 = fb_w;
    if (y1 > fb_h) y1 = fb_h;

    for (int y = y0; y < y1; y++) {
        uint16_t *row = fb + (size_t)y * fb_w + x0;
        for (int x = x0; x < x1; x++) {
            *row++ = color;
        }
    }
}

static void draw_char_rgb565(uint16_t *fb, int fb_w, int fb_h,
                             int x, int y, char c, int scale,
                             uint16_t fg, uint16_t bg)
{
    const uint8_t *glyph = font_glyph(c);

    for (int row = 0; row < FONT_H; row++) {
        for (int col = 0; col < FONT_W; col++) {
            uint16_t color = (glyph[row] >> col) & 0x1 ? fg : bg;
            int px = x + col * scale;
            int py = y + row * scale;
            fill_rect_rgb565(fb, fb_w, fb_h, px, py, px + scale, py + scale, color);
        }
    }
}

static void draw_string_rgb565(uint16_t *fb, int fb_w, int fb_h,
                               int x, int y, const char *s, int scale,
                               uint16_t fg, uint16_t bg)
{
    int step = FONT_W * scale;
    for (const char *p = s; *p; p++, x += step) {
        draw_char_rgb565(fb, fb_w, fb_h, x, y, *p, scale, fg, bg);
    }
}

void app_overlay_draw_fps(uint16_t *fb, int fb_w, int fb_h, float fps)
{
    if (fb == NULL || fb_w <= 0 || fb_h <= 0) {
        return;
    }
    if (fps < 0.0f || fps > 999.9f) {
        fps = 999.9f;
    }

    char line[24];
    int whole = (int)fps;
    int tenth = (int)(fps * 10.0f) % 10;
    snprintf(line, sizeof(line), "FPS:%3d.%d", whole, tenth);

    int text_w = (int)strlen(line) * FONT_W * OVERLAY_SCALE;
    int text_h = FONT_H * OVERLAY_SCALE;
    int x0 = 8;
    int y0 = 8;

    /* black box behind the text for readability over a live image */
    fill_rect_rgb565(fb, fb_w, fb_h,
                     x0, y0,
                     x0 + text_w + 2 * OVERLAY_PAD,
                     y0 + text_h + 2 * OVERLAY_PAD,
                     0x0000);

    draw_string_rgb565(fb, fb_w, fb_h,
                       x0 + OVERLAY_PAD, y0 + OVERLAY_PAD,
                       line, OVERLAY_SCALE,
                       0xFFFF /* white */, 0x0000 /* black */);
}

